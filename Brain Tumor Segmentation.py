import cv2
import matplotlib.pyplot as plt

# Read the MRI image
img = cv2.imread('/content/mri1.tif', cv2.IMREAD_UNCHANGED)

# OpenCV loads images in BGR format, not RGB
img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

# Extract individual components
R = img[:, :, 0]
G = img[:, :, 1]
B = img[:, :, 2]

# Display the original image and its components
plt.figure(figsize=(12, 8))

plt.subplot(2, 2, 1)
plt.imshow(img)
plt.title("Original MRI Image")
plt.axis("off")

plt.subplot(2, 2, 2)
plt.imshow(R, cmap="gray")
plt.title("Red Component")
plt.axis("off")

plt.subplot(2, 2, 3)
plt.imshow(G, cmap="gray")
plt.title("Green Component")
plt.axis("off")

plt.subplot(2, 2, 4)
plt.imshow(B, cmap="gray")
plt.title("Blue Component")
plt.axis("off")

plt.tight_layout()
plt.show()

"""Converting the RGB image into Gray scale image using formula
 ---> Gray=0.298×R+0.587×G+0.114×B
"""

import matplotlib.pyplot as plt

gray = 0.299 * R + 0.587 * G + 0.114 * B
gray = gray.round().clip(0, 255).astype("uint8")

plt.imshow(gray, cmap="gray")
plt.title("Grayscale Image")
plt.axis("off")
plt.show()

"""Applying median filtering to reduce noise"""

import cv2
import matplotlib.pyplot as plt

median = cv2.medianBlur(gray, 3)

plt.imshow(median, cmap="gray")
plt.title("Median Filter")
plt.axis("off")
plt.show()

"""Thresholding is done to convert Gray scale image into Binary image. Here we have used constant thresholding with threshold T=90."""

_, binary = cv2.threshold(median, 90, 255, cv2.THRESH_BINARY)

plt.imshow(binary, cmap='gray')
plt.title("Constant Thresholding (T = 90)")
plt.axis('off')
plt.show()

"""Connected components labelling and calculating metrics:
1) Bounded box = (x,y,w,h)
    
    (x,y) -> coordinates of top left corner of the rectangle which perfectly fits the component
    w -> width of the rectangle
    h -> height of the rectangle

2) area = number of foreground pixels in the component

3) Bounded box area = w * h

4) density = area / Bounded box area
"""

import cv2
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Step 1: Convert the existing binary image to 0 and 1
binary01 = (binary > 0).astype(np.uint8)

# Step 2: Label connected components and calculate their statistics
num_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(
    binary01,
    connectivity=8
)

print("Number of components, including background:", num_labels)
print("Total foreground components:", num_labels - 1)

# Step 3: Extract features of each foreground component
results = []

for i in range(1, num_labels):

    # Bounding box coordinates and dimensions
    x = int(stats[i, cv2.CC_STAT_LEFT])
    y = int(stats[i, cv2.CC_STAT_TOP])
    w = int(stats[i, cv2.CC_STAT_WIDTH])
    h = int(stats[i, cv2.CC_STAT_HEIGHT])

    # Number of foreground pixels
    area = int(stats[i, cv2.CC_STAT_AREA])

    # Bounding box area
    bbox_area = w * h

    # Component density
    density = area / bbox_area if bbox_area > 0 else 0

    results.append({
        "Component": i,
        "Area (pixels)": area,
        "Density": round(density, 4),
        "Bounding Box (x, y, w, h)": (x, y, w, h),
        "Bounding Box Area": bbox_area
    })

# Step 4: Create and display the feature table
df = pd.DataFrame(results)

print("\nConnected Component Features:")
display(df)

# Step 5: Display the connected-components plot
plt.figure(figsize=(8, 8))
plt.imshow(labels, cmap="nipy_spectral", interpolation="nearest")
plt.title("Connected Components")
plt.axis("off")
plt.show()

"""Selecting expected Tumor candidates based on the criteria:
area >= 1000 and density >= 0.4
"""

import numpy as np
import pandas as pd

selected_candidates = []
candidate_mask = np.zeros_like(binary, dtype=np.uint8)

for result in results:
    area = result["Area (pixels)"]
    density = result["Density"]
    i = result["Component"]
    x, y, w, h = result["Bounding Box (x, y, w, h)"]

    if area > 1000 and density > 0.4:
        selected_candidates.append({
            "Component": i,
            "Area (pixels)": area,
            "Density": density,
            "X": x,
            "Y": y,
            "Width": w,
            "Height": h
        })

        candidate_mask[labels == i] = 255

# Display selected candidates as a DataFrame
selected_df = pd.DataFrame(
    selected_candidates,
    columns=[
        "Component", "Area (pixels)", "Density",
        "X", "Y", "Width", "Height"
    ]
)

print("Selected candidates:")
display(selected_df)

# Display the selected component mask
import matplotlib.pyplot as plt

plt.figure(figsize=(8, 8))
plt.imshow(candidate_mask, cmap="gray")
plt.title("Selected Tumor Candidates")
plt.axis("off")
plt.show()

"""Checking whether the result is acceptable or not based on criteria :
Dice Score >= 0.8
"""

import cv2
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Your predicted mask
pred = (candidate_mask > 0)

# Load the ground-truth mask
ground_truth_img = cv2.imread(
    "/content/result1.tif",
    cv2.IMREAD_GRAYSCALE
)

if ground_truth_img is None:
    raise FileNotFoundError("Ground-truth mask image not found.")

# Convert to binary mask
gt = (ground_truth_img > 0)

# Ensure both masks have the same dimensions
if pred.shape != gt.shape:
    raise ValueError(
        f"Mask dimensions differ: predicted={pred.shape}, "
        f"ground truth={gt.shape}"
    )

# Calculate pixel counts
TP = np.sum(pred & gt)       # Correctly predicted tumor pixels
FP = np.sum(pred & ~gt)      # Incorrectly predicted tumor pixels
FN = np.sum(~pred & gt)      # Missed tumor pixels
TN = np.sum(~pred & ~gt)     # Correctly predicted background pixels

# Calculate metrics safely
dice = (2 * TP) / (2 * TP + FP + FN) if (2 * TP + FP + FN) else 1.0
iou = TP / (TP + FP + FN) if (TP + FP + FN) else 1.0
precision = TP / (TP + FP) if (TP + FP) else 1.0
recall = TP / (TP + FN) if (TP + FN) else 1.0
accuracy = (TP + TN) / (TP + TN + FP + FN)

# Display metrics as a table
metrics_df = pd.DataFrame({
    "Metric": ["Dice Score", "IoU", "Precision", "Recall", "Accuracy"],
    "Value": [dice, iou, precision, recall, accuracy]
})

display(metrics_df.round(4))

plt.figure(figsize=(8, 8))
plt.imshow(ground_truth_img, cmap="gray")
plt.title("Selected Tumor Candidates")
plt.axis("off")
plt.show()